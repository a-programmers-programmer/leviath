#!/usr/bin/env python3
"""Generate the typed-Python counterpart of the accepted contract SDL.

This is the *real-artifact* half of GQL-02's proof.  The synthetic ``Order``
domain in :mod:`leviath_reconcile.scenarios` proves the reconciliation rules; it
does not prove that the two **adapters** agree on the **accepted contract**.
This script produces the code-side artifact for that proof:

    docs/workflow/schema-workflow.graphql   (GQL-01's accepted SDL, read-only)
        ->  python/leviath_reconcile/fixtures/workflow_model.py   (generated once, checked in)

The generated module is a plain typed Python module — dataclasses for SDL object
types, ``enum.Enum`` subclasses for SDL enums, ``NewType``/aliases for scalars —
so the code adapter reads it with :mod:`ast` alone, exactly as it reads any real
module.  It is generated **once** and committed, so the reconciliation proof is
between two independently-authored artifacts, not between an artifact and itself.

Usage:
    python3 tools/generate_code_counterpart.py [SDL] [OUT]

Exit 0 on write, 1 on failure.  No network, no provider, no secret.
"""

from __future__ import annotations

import sys
from pathlib import Path

from graphql import (
    build_schema,
    is_enum_type,
    is_input_object_type,
    is_interface_type,
    is_list_type,
    is_non_null_type,
    is_object_type,
    is_scalar_type,
    is_union_type,
)

#: SDL scalar -> the Python spelling that means the *same* canonical domain type
#: through the crosswalk.  A scalar is a leaf type with no structure to model, so
#: the counterpart is a type *alias*, not a ``NewType``: the code adapter reads an
#: alias as a type-level symbol, which is the counterpart of an SDL scalar
#: declaration.  Emitting a ``NewType`` call instead would read as a module-level
#: *value*, and every scalar would look like an existence divergence.
PY_SCALAR_ALIAS = {
    "ID": "str",
    "String": "str",
    "Int": "int",
    "Float": "float",
    "Boolean": "bool",
    "DateTime": "datetime.datetime",
    "Decimal": "decimal.Decimal",
    "Duration": "datetime.timedelta",
    "URI": "AnyUrl",
    "UUID": "UUID",
    "Confidential": "str",
    "PortValue": "object",
    "JsonPointer": "str",
}

#: SDL base type -> the Python annotation that means the *same* canonical domain
#: type through the crosswalk.  A type the table does not know is emitted as a
#: forward reference to its own generated class, so an unknown type surfaces as a
#: real divergence rather than being smoothed away.
PY_ANNOTATION = {
    "ID": "str",
    "String": "str",
    "Int": "int",
    "Float": "float",
    "Boolean": "bool",
    "DateTime": "datetime",
    "Decimal": "decimal.Decimal",
    "Duration": "timedelta",
    "URI": "AnyUrl",
    "Confidential": "Confidential",
    "PortValue": "PortValue",
}

#: SDL scalars that are not aliased to a builtin and therefore get a NewType.
OPAQUE_SCALARS = {"Confidential", "PortValue", "JsonPointer"}

#: GraphQL's built-in scalars.  They are always present in a built schema's
#: ``type_map`` but the accepted SDL does **not** declare them, so emitting a
#: Python counterpart would create a symbol the schema projection never
#: declares.  They are skipped; field annotations still spell them as the
#: matching Python builtin.
BUILTIN_SCALARS = {"Boolean", "String", "ID", "Int", "Float"}

HEADER = '''"""Typed-Python counterpart of the accepted workflow contract (GENERATED).

Generated by ``tools/generate_code_counterpart.py`` from
``docs/workflow/schema-workflow.graphql`` — the SDL whose printed-SHA-256
fingerprint GQL-01 accepted.  **Do not hand-edit**: regenerate instead, so the
two artifacts stay independently authored but semantically paired.

This module is the code-side artifact of GQL-02's real-artifact proof: the code
adapter reads it with :mod:`ast` alone (no import, no exec), and the reconciler
must find the two real projections in agreement.
"""

from __future__ import annotations

import datetime
import decimal
from dataclasses import dataclass
from enum import Enum
from typing import Any, NewType, Protocol
from uuid import UUID

from pydantic import AnyUrl


'''


def py_type(gql_type) -> str:
    """Render a GraphQL type reference as a Python annotation."""
    if is_non_null_type(gql_type):
        return py_type(gql_type.of_type)
    if is_list_type(gql_type):
        return f"list[{py_type(gql_type.of_type)}]"
    name = gql_type.name
    if name in PY_ANNOTATION:
        return PY_ANNOTATION[name]
    return name


def is_nullable(gql_type) -> bool:
    return not is_non_null_type(gql_type)


def render_enum(name: str, values) -> str:
    lines = [f"class {name}(Enum):"]
    for value_name, _value in values:
        lines.append(f'    {value_name} = "{value_name}"')
    if len(lines) == 1:
        lines.append("    pass")
    return "\n".join(lines)


def render_object(name: str, fields, *, kind: str) -> str:
    if kind == "interface":
        # An SDL interface is a *shape* several types implement, not a concrete
        # record.  A ``Protocol`` is the Python construct with that meaning, so
        # the code projection declares the same role (``interface``) instead of
        # declaring a dataclass and reading as a concrete type.
        lines = [f"class {name}(Protocol):"]
        if not fields:
            lines.append("    pass")
            return "\n".join(lines)
        for field_name, field in fields:
            annotation = py_type(field.type)
            if is_nullable(field.type):
                annotation = f"{annotation} | None"
            lines.append(f"    {field_name}: {annotation}")
        return "\n".join(lines)
    lines = ["@dataclass", f"class {name}:"]
    if not fields:
        lines.append("    pass")
        return "\n".join(lines)
    for field_name, field in fields:
        annotation = py_type(field.type)
        if is_nullable(field.type):
            annotation = f"{annotation} | None"
            default = " = None"
        else:
            default = ""
        lines.append(f"    {field_name}: {annotation}{default}")
    return "\n".join(lines)


def render_union(name: str, types) -> str:
    members = " | ".join(t.name for t in types)
    return f"{name} = {members}" if members else f"{name} = Any"


def render_scalar(name: str) -> str:
    """A type alias, so the code adapter reads a type-level symbol.

    An SDL ``scalar Confidential`` is a *declaration*; ``Confidential = str`` is
    the Python declaration of the same type name.  A ``NewType(...)`` call would
    read as a module-level value instead, which is a different role and would
    show up as a spurious existence divergence on every scalar in the contract.
    """
    target = PY_SCALAR_ALIAS.get(name, "object")
    return f"{name} = {target}"


def generate(sdl_path: Path) -> str:
    schema = build_schema(sdl_path.read_text(encoding="utf-8"))
    blocks = [HEADER]
    for name, gql_type in sorted(schema.type_map.items()):
        if name.startswith("__") or name in ("Query", "Mutation", "Subscription"):
            continue
        if name in BUILTIN_SCALARS:
            continue
        if is_enum_type(gql_type):
            blocks.append(render_enum(name, sorted(gql_type.values.items())))
        elif is_object_type(gql_type) or is_interface_type(gql_type) or is_input_object_type(gql_type):
            kind = "interface" if is_interface_type(gql_type) else "type"
            blocks.append(
                render_object(name, sorted(gql_type.fields.items()), kind=kind)
            )
        elif is_union_type(gql_type):
            blocks.append(render_union(name, gql_type.types))
        elif is_scalar_type(gql_type):
            rendered = render_scalar(name)
            if rendered:
                blocks.append(rendered)
    return "\n\n".join(block for block in blocks if block.strip()) + "\n"


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    here = Path(__file__).resolve().parent.parent
    sdl = Path(argv[0]) if argv else here / "docs/workflow/schema-workflow.graphql"
    out = Path(argv[1]) if len(argv) > 1 else here / "python/leviath_reconcile/fixtures/workflow_model.py"
    if not sdl.is_file():
        print(f"FAIL: SDL not found: {sdl}", file=sys.stderr)
        return 1
    text = generate(sdl)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} ({len(text)} bytes) from {sdl}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())