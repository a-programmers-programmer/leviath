#!/usr/bin/env python3
"""Embed the HarnessQL references as agent tools (work order GQL-09).

Before GQL-09 the bake-off lane read the Composition Guide off a scratch path
(`/data/work/leviath/study/composition-guide.md`) that only existed on one box,
and the merge lane needed a file read at all. Both references are now static
agent tools, generated from the in-repo markdown by this script - the same
pattern `graphql-schema` uses for `graphql_contract_guide`:

    python3 scripts/generate_tools.py           # (re)generate
    python3 scripts/generate_tools.py --check    # verify the tools match the source

`--check` exits non-zero when a generated tool is missing or stale, so a
divergence between the guide and the tool is a test failure, not a surprise at
run time.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
AGENT_DIR = HERE.parent
MERGE_DIR = AGENT_DIR.parent / "bake-merge"

TOOLS = [
    {
        "tool": "composition_guide",
        "description": (
            "Read the HarnessQL Composition Guide, the arbiter for every bake-off "
            "change. A static bundled reference: no file read and no scratch path."
        ),
        "source": AGENT_DIR / "references" / "composition-guide.md",
        "target": AGENT_DIR / "tools" / "composition_guide.rhai",
        "header": "// Generated by scripts/generate_tools.py; edit references/composition-guide.md.\n",
    },
    {
        "tool": "merge_decision_format",
        "description": (
            "Read the exact harnessql-merge-decisions/v1 JSON decision format the "
            "merge lane must emit. A static bundled reference: the merge lane has "
            "no file tools at all."
        ),
        "source": MERGE_DIR / "references" / "merge-decision-format.md",
        "target": MERGE_DIR / "tools" / "merge_decision_format.rhai",
        "header": "// Generated by scripts/generate_tools.py; edit references/merge-decision-format.md.\n",
    },
]


def render(entry: dict) -> str:
    body = entry["source"].read_text(encoding="utf-8")
    return (
        entry["header"]
        + f"// @tool {entry['tool']}\n"
        + f"// @description {entry['description']}\n\n"
        + json.dumps(body)
        + "\n"
    )


def main(argv: list[str]) -> int:
    check = "--check" in argv
    failures = 0
    for entry in TOOLS:
        if not entry["source"].is_file():
            print(f"MISSING SOURCE {entry['source']}", file=sys.stderr)
            return 2
        expected = render(entry)
        if check:
            actual = entry["target"].read_text(encoding="utf-8") if entry["target"].is_file() else None
            if actual != expected:
                print(f"STALE {entry['target']}: regenerate with scripts/generate_tools.py",
                      file=sys.stderr)
                failures += 1
            else:
                print(f"OK {entry['target']}")
            continue
        entry["target"].parent.mkdir(parents=True, exist_ok=True)
        entry["target"].write_text(expected, encoding="utf-8")
        print(f"wrote {entry['target']} ({len(expected)} bytes)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
